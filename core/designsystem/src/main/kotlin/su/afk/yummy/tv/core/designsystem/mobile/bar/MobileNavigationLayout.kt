package su.afk.yummy.tv.core.designsystem.mobile.bar

/** Как главная навигация мобильного UI сейчас расположена относительно контента. */
enum class MobileNavigationLayout {
    /** Нижний бар на компактной ширине, контент заканчивается над ним. */
    BottomBar,

    /** Боковая рейка на планшете, развёрнутом складном или в широком окне. */
    Rail,

    /** Навигация скрыта: вне корня таба, в плеере, на обязательном обновлении. */
    Hidden,
}
