package su.afk.yummy.tv.core.utils.logging

import kotlinx.coroutines.flow.Flow

/**
 * Включена ли запись логов приложения в файл (Настройки → Общие → «Запись логов»).
 * По умолчанию выключена: пока флаг снят, коллектор не запущен, диагностика плеера в файл не
 * пишется, файлы логов стёрты, а «Поделиться логами» скрыто. Реализация живёт в `core:preferences`.
 */
interface AppLogRecordingSettings {

    /**
     * Реальные значения из хранилища, без стартового значения по умолчанию: первое событие — то, что
     * пользователь выбрал на самом деле. Нужен коллектору, чтобы отличить «ещё не прочитано» от
     * «выключено» (только выключение стирает файлы).
     */
    val enabled: Flow<Boolean>

    /** Текущее значение для писателей логов, которым ждать хранилище нельзя; до чтения — `false`. */
    val isEnabled: Boolean
}
