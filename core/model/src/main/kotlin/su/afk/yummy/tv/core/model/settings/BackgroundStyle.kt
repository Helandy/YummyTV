package su.afk.yummy.tv.core.model.settings

/**
 * Режим оформления интерфейса, выбираемый независимо от палитры-акцента [AppTheme].
 *
 * [SYSTEM] — следовать системной теме устройства; [LIGHT] — светлая схема с тёмным текстом;
 * [DARK] — тёмная схема (как исторически); [AMOLED] — тёмная схема с чисто чёрным фоном
 * для OLED-экранов (работает поверх любой палитры, включая системную).
 */
enum class BackgroundStyle {
    SYSTEM,
    LIGHT,
    DARK,
    AMOLED,
}
