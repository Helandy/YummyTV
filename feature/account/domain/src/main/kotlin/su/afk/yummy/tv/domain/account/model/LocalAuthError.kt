package su.afk.yummy.tv.domain.account.model

/**
 * Причина сбоя передачи сессии. Текст для пользователя собирает UI — data-слой не знает о локали.
 */
enum class LocalAuthError {
    /** Введён неверный PIN (или тело запроса повреждено). Код остаётся прежним. */
    INVALID_PIN,

    /** Истёк срок жизни PIN. Нужен новый код. */
    PIN_EXPIRED,

    /** Исчерпан лимит неудачных попыток. Нужен новый код. */
    TOO_MANY_ATTEMPTS,

    /** Не удалось анонсировать сервис в локальной сети. */
    SERVICE_UNAVAILABLE,

    /** Нет разрешения на работу в локальной сети — без него NSD не стартует. */
    PERMISSION_DENIED,

    /** PIN верный, но завершить вход по полученному токену не удалось. */
    SIGN_IN_FAILED,
}
