package su.afk.yummy.tv.domain.account.model

/**
 * Формат кода сопряжения: десять символов из цифр и заглавных букв, разбитые на две группы по пять.
 *
 * Почему не шесть цифр, как было: код — единственный секрет, которым защищена передача сессии, и
 * перехвативший трафик перебирает его офлайн, где лимит попыток на ТВ уже не работает. Шесть цифр —
 * это 10^6 вариантов, то есть минуты работы видеокарты. Десять символов из этого алфавита дают
 * порядка 4·10^14 (~2^48), и офлайн-перебор перестаёт быть вектором.
 *
 * Из алфавита выброшены буквы, которые на экране телевизора путаются с цифрами (B, G, I, L, O, Q,
 * S, Z), а при вводе они же приводятся к цифрам-двойникам: человек читает код с дивана и ошибается
 * именно здесь, а не в редких символах.
 */
object LocalAuthCode {
    const val LENGTH = 10
    const val GROUP_SIZE = 5

    const val ALPHABET = "0123456789ACDEFHJKMNPRTUVWXY"

    private val CONFUSABLES = mapOf(
        'B' to '8',
        'G' to '6',
        'I' to '1',
        'L' to '1',
        'O' to '0',
        'Q' to '0',
        'S' to '5',
        'Z' to '2',
    )

    /** Приводит ввод к алфавиту кода: регистр, двойники цифр, всё лишнее отбрасывается. */
    fun normalize(raw: String): String = raw
        .uppercase()
        .map { char -> CONFUSABLES[char] ?: char }
        .filter { char -> char in ALPHABET }
        .joinToString(separator = "")
}
